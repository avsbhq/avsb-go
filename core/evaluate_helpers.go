package core

import "encoding/json"

// Lookup and construction helpers for the evaluator, plus the small exported
// accessors the SDK layer needs for its client-layer pipeline (sticky lookup
// and runtime overrides both resolve a flag and a variation before the
// evaluator runs).

// resolvedBandit is the bandit a bandit-typed rule points at, plus the key
// that addresses its model.
type resolvedBandit struct {
	Key    string
	Config BanditConfig
}

// resolveRuleBandit resolves the bandit for a bandit-typed rule. A shared
// BanditID (joined against Datafile.Bandits) wins over an inline config, and
// the resolved key is what addresses the model store: the shared entry's Key,
// or the rule's own id for an inline config.
func resolveRuleBandit(rule *Rule, df *Datafile) *resolvedBandit {
	if rule.BanditID != "" {
		for i := range df.Bandits {
			if df.Bandits[i].ID == rule.BanditID {
				return &resolvedBandit{Key: df.Bandits[i].Key, Config: df.Bandits[i].Config}
			}
		}
		return nil
	}
	if rule.Bandit != nil {
		return &resolvedBandit{Key: rule.ID, Config: *rule.Bandit}
	}
	return nil
}

// reasonVariationKey renders a variation key for a reason string.
//
// It prints "undefined" for a missing variation on purpose. The reason strings
// are compared byte for byte against fixtures generated by the TypeScript
// reference, whose template interpolates `${targetVar?.key}` and therefore
// writes the literal "undefined" when a rule points at a variation that was
// deleted from the flag. No fixture covers that state today, but if one is
// ever generated, this port matches it instead of quietly differing.
func reasonVariationKey(v *Variation) string {
	if v == nil {
		return "undefined"
	}
	return v.Key
}

func findFlag(df *Datafile, key string) *FlagEntry {
	for i := range df.Flags {
		if df.Flags[i].Key == key {
			return &df.Flags[i]
		}
	}
	return nil
}

func variationByID(flag *FlagEntry, id string) *Variation {
	for i := range flag.Variations {
		if flag.Variations[i].ID == id {
			return &flag.Variations[i]
		}
	}
	return nil
}

// VariationByID returns the flag's variation with the supplied id, or nil.
// Exported for the SDK layer's sticky-bucket resolution, which resolves a
// stored assignment by variation ID.
func VariationByID(flag *FlagEntry, id string) *Variation {
	return variationByID(flag, id)
}

// FindFlag returns the datafile entry for a flag key, or nil. Exported for the
// SDK layer's sticky and runtime-override paths.
func FindFlag(df *Datafile, key string) *FlagEntry {
	if df == nil {
		return nil
	}
	return findFlag(df, key)
}

// VariationByKey returns the flag's variation with the supplied key, or nil.
// Runtime overrides are addressed by variation KEY (that is what an operator
// types), while sticky assignments are addressed by ID.
func VariationByKey(flag *FlagEntry, key string) *Variation {
	if flag == nil {
		return nil
	}
	for i := range flag.Variations {
		if flag.Variations[i].Key == key {
			return &flag.Variations[i]
		}
	}
	return nil
}

func buildEval(
	v *Variation,
	defaultValue json.RawMessage,
	source string,
	ruleID *string,
	ruleType *string,
) FlagEvaluation {
	f := FlagEvaluation{Source: source, RuleID: ruleID, RuleType: ruleType}
	if v == nil {
		f.Value = defaultValue
		return f
	}
	f.Value = v.Value
	k := v.Key
	f.VariationKey = &k
	return f
}
